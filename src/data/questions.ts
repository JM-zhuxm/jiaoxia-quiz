/** 把每题写在 A 的正确答案按顺序均匀轮转到 A/B/C/D，避免答案位置过于集中。 */
export function distributeAnswers(raw: readonly RawQuestion[]): QuizQuestion[] {
  return raw.map((question, index) => {
    const shift = index % 4;
    const options = question.options.slice(shift).concat(question.options.slice(0, shift));
    return {
      id: question.id,
      text: question.text,
      options,
      answer: (0 - shift + options.length) % options.length,
      explanation: question.explanation,
      art: question.art,
    };
  });
}

